CATS = [(n, re.compile(r, re.I)) for n, r in CATS]
STOP = {"набор","комплект","для","из","с","на","и","в","по","от","шт","new","нов","новый","подарок"}

def clean_title(t):
    t = re.split(r'\n', t.strip())[0] if t.strip() else ""
    t = PRICE_RE.sub(" ", t)
    t = re.sub(r'(?:Цена|Акция|Только сегодня|Большой ассортимент)\b.*$', '', t, flags=re.I)
    t = re.sub(r'[🔥❗]+', '', t)
    return re.sub(r'\s+', ' ', t).strip(" -,.:;")

def norm(t):
    return re.sub(r'[^a-zа-я0-9]+', ' ', t.lower().replace('ё','е')).strip()

def price_of(t):
    m = PRICE_RE.findall(t)
    if not m: return None
    v = int(re.sub(r'\D', '', m[-1]))
    return v if 20 <= v <= 1_000_000 else None

items = []
for p in posts.values():
    if not p["photos"] and not p["text"]: continue
    price = price_of(p["text"])
    if price is None and not p["photos"]: continue   # служебные объявления
    first = p["text"].split("\n")[0] if p["text"] else ""
    title = clean_title(p["text"]) or first
    if not title or len(re.findall(r"[A-Za-zА-Яа-я]", title)) < 5 or re.match(r"(Срок до|\d)", title): continue
    if re.match(r'^(Уважаемые|Режим работы|СЕГОДНЯ|Сегодня)', p["text"]) and price is None: continue
    cat = "Разное"
    for src in (title, p["text"]):
        for n, rx in CATS:
            if rx.search(src): cat = n; break
        if cat != "Разное": break
    used = bool(re.search(r'\bб/?у\b|бывш', p["text"], re.I))
    promo = bool(re.search(r'акци|скидк|только сегодня|🔥', p["text"], re.I))
    items.append({"id": p["id"], "date": p["date"], "title": title[:160], "price": price, "cat": cat,
                  "used": used, "promo": promo, "photos": p["photos"][:3], "text": p["text"]})

# дубли: один и тот же товар выкладывают повторно, держим последний пост + историю
groups = defaultdict(list)
for it in items: groups[norm(it["title"])[:80]].append(it)
catalog = []
for k, g in groups.items():
    g.sort(key=lambda x: x["id"])
    last = dict(g[-1])
    last["reposts"] = len(g) - 1
    last["first_seen"] = g[0]["date"]
    last["prices"] = [x["price"] for x in g if x["price"]]
    last["price_prev"] = next((x["price"] for x in reversed(g[:-1]) if x["price"] and x["price"] != last["price"]), None)
    catalog.append(last)
catalog.sort(key=lambda x: -x["id"])

# фото: скачиваем и сжимаем только свежим
os.makedirs("site/img", exist_ok=True)
cutoff = now - datetime.timedelta(days=DAYS)
def grab(it):
    out = []
    if datetime.datetime.fromisoformat(it["date"]) < cutoff: return out
    for i, u in enumerate(it["photos"][:1]):   # одно фото для карточки
        fn = f"img/{it['id']}.jpg"
        if not os.path.exists("site/" + fn):
            tmp = f"site/{fn}.src"
            r = subprocess.run(["curl", "-sL", "-m", "30", "-o", tmp, u])
            try:
                from PIL import Image
                im = Image.open(tmp).convert("RGB"); im.thumbnail((640, 640)); im.save("site/" + fn, quality=78)
            except Exception:
                pass
            if os.path.exists(tmp): os.remove(tmp)
        if os.path.exists("site/" + fn): out.append(fn)
    return out
with cf.ThreadPoolExecutor(8) as ex:
    imgs = list(ex.map(grab, catalog))
for it, im in zip(catalog, imgs):
    it["img"] = im[0] if im else None
    del it["photos"]; del it["text"]
catalog = [c for c in catalog if c["img"]]   # в каталоге только то, что есть с фото

meta = {"updated": latest, "total": len(catalog), "channel": "rasprodonetsk"}
with open("site/data.js", "w", encoding="utf8") as f:
    f.write("window.CATALOG=" + json.dumps({"meta": meta, "items": catalog}, ensure_ascii=False, separators=(",", ":")) + ";")
